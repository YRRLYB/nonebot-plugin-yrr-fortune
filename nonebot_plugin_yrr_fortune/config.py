# --- 插件配置（NoneBot 会读取同名大写下划线环境变量） -------------------------
class Config(BaseModel):
    """所有配置都有默认值，因此插件可以零配置加载。"""

    fortune_background_url: str = "https://photo.yrrlyb.top/api.php?sort=mp"
    fortune_preload_count: int = 8
    fortune_http_timeout: float = 30.0
    fortune_max_message_map: int = 500
    fortune_insecure_ssl: bool = False


# 原配置里每个等级都有大量重复句子（同一句出现两次），去重后既省内存，
# 也让“今日签文”不再反复抽到同一句。
for _level in list(fortune_texts):
    fortune_texts[_level] = list(dict.fromkeys(fortune_texts[_level]))
